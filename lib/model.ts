  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.75,
  maturity_range: 0.45,
  maturity_days: 1095,
  unknown_age_multiplier: 0.9,
  chain_step: 0.02,
  chain_cap: 10,
  peer_floor: 0.05,
  peer_cap: 1.5,
