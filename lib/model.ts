// Token Radar: the model behind token-radar-01.
//
// Reads the sealed DefiLlama snapshot and ranks every pre-token protocol that is not a
// wrapped, staked or bridged product of a token that already trades. The board's implied
// value is this entry's own claim, derived only from the snapshot's own figures:
//
//   implied = TVL x peerMultiple x growthMult x maturityMult x chainMult
//
//   peerMultiple  the category's median market-cap / TVL among live-token protocols
//                 (shrunk toward the global median when the category has few peers,
//                 clamped to 0.05..1.50; a category prices from its own peers only
//                 when at least 3 live protocols trade there, else the global median
//                 0.2227 — one outlier peer must not set the price). A protocol's
//                 launch is priced like its own category trades, not like a
//                 hand-picked name.
//   growthMult    1 + clamp(change_7d, -50, +100) / 100 x 0.6   -> 0.70..1.60
//   maturityMult  0.75 + min(age_days, 1095) / 1095 x 0.45       -> 0.75..1.20
//                 (age unknown: 0.90). Longer-running with no token yet: more pent-up value.
//   chainMult     1 + 0.02 x min(chains - 1, 10)                 -> 1.00..1.20
//
// No protocol name is ever special-cased: the same function scores every row. Protocols
// whose token already trades are kept apart in the Live view and shown at the market's
// own value, never mixed into the ranked board.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

